/** The application code
 * This is called from the CubeMX generated main() function after all initialization has completed */

#include <stdio.h>
#include <stdbool.h>

#include "stm32l4xx_hal.h"

#include "user_io.h"
#include "modem_at.h"
#include "app_iwdg.h"
#include "dht22.h"
#include "led.h"
#include "app.h"

// 2026-01-01T00:00:00 as an Epoch
#define EPOCH_START_2026	1767225600ul

// TODO: configuration data
static const char *APN = "TM";
static const char *HTP_HOSTS[] = {"www.google.com", "www.cloudflare.com", "aws.amazon.com", "www.microsoft.com"};
static const int DEBUG_LEVEL = 5;

// private forward declarations
static bool ModemServiceUp (int n_retries);
static bool ModemServiceDown (void);
static void WatchdogCallback (void);

/**
 * @brief the main application, called from the main function that is
 *        generated by CubeMX */
void App (void) {

	DebugInit (DEBUG_LEVEL);
	printf ("\r\nBoat Environment Monitor starting\r\n");
	PrintDiagnostics ();

	// bring up the modem
	printf ("App: Setting up modem\r\n");
	bool modem_service_up = ModemServiceUp (3);

	// even if the modem isn't available, it may still be possible to read its real-time clock
	time_t rtc_time;
	bool status = ModemGetRTCTime (&rtc_time, 3);
	// if the real-time clock is before 2026-01-01T00:00:00 then assume it
	// has never been set, and so isn't usable
    bool modem_clock_valid = true;
	if (rtc_time < EPOCH_START_2026)
		modem_clock_valid = false;

	// read DHT22 sensors until a NO_SENSOR return from the reading function
	printf ("App: Reading DLT22 sensors\r\n");
	DHT22Reading_t readings [N_DHT22_SENSORS];
	int n_dht22_readings = 0;
	bool dht22_clock_valid = DHT22Init ();
	bool dht22_status = true;
	if (dht22_clock_valid) {
		bool continue_reading = true;
		for (DHT22SensorID_t sensor = DHT22_1; (sensor < N_DHT22_SENSORS) && continue_reading; sensor++) {
			DHT22ReadingStatus_t rd_status = DHT22TakeReading (sensor, &(readings[n_dht22_readings]));
			switch (rd_status) {
				case DHT22_READING_OK:
					n_dht22_readings += 1;
					break;
				case DHT22_NO_SENSOR:
					// the "no sensor" return is used to automatically detect
					// whether a sensor is present - sensors must be connected
					// in order starting at number 1
					continue_reading = false;
					break;
				default:
					continue_reading = false;
					dht22_status = false;
			}
		}
	}	

	// bring down the modem
	printf ("App: Bringing down modem\r\n");
    status = ModemServiceDown ();
	if (! status)
		modem_service_up = false;

	// end of program
	printf ("App: Program finished, status:\r\n"); 
	printf ("  Modem RTC clock: %s\r\n", modem_clock_valid ? "valid" : "not valid");
	printf ("  Modem service: %s\r\n", modem_service_up ? "up" : "not up");
	printf ("  DHT22 clock: %s\r\n", dht22_clock_valid ? "valid" : "not valid");
	printf ("  DHT22 status: %s\r\n", dht22_status ? "ok" : "not ok");
	printf ("  Number of DHT22 readings: %d\r\n", n_dht22_readings);

	// work out what to display on the LED
	LEDPattern_t pattern;
	if (! modem_clock_valid) pattern = LED_CLOCK_ERROR;
	else if (! modem_service_up) pattern = LED_MODEM_ERROR;
	else if (! dht22_clock_valid) pattern = LED_CLOCK_ERROR;
	else if (! dht22_status) pattern = LED_DHT22_ERROR;
	else pattern = LED_SUCCESS;
	BlinkLEDForever (pattern, WatchdogCallback);	
}

/**
 * @brief start the Modem service
 * @param n_retries the number of times to try restarting the modem
 */
static bool ModemServiceUp (int n_retries) {
	// Modem setup...
	bool modem_status = false;
	for (int n_retries = 0; (n_retries < 3) && (! modem_status); n_retries ++) {
		// Initialise the modem data structures
		modem_status = ModemInit (WatchdogCallback);
		
		// Start modem comms
		if (modem_status)
			modem_status = ModemStart ();

		// Check comms to the modem
		if (modem_status)
			modem_status = ModemTestComms (3);
	
		// Check the modem is in full functionality mode
		if (modem_status)
			modem_status = ModemCheckFullFunctionality (3);

		// check the SIM is ready
		if (modem_status)
			modem_status = ModemCheckSIMReady (5);

		// check that the modem is in automatic operator selection mode
		if (modem_status)
			modem_status = ModemCheckAutoOperSelMode (3);

		// check that the modem is registered with the mobile network
		if (modem_status)
			modem_status = ModemCheckRegistered (10);

		// check the received signal strength (mainly of interest for debugging, but would
		// be useful if it could be communicated in normal use, as it would show when the
		// modem is out of range from a cell tower)
		int rssi = 999;
		if (modem_status) {
			rssi = ModemGetSignalStrength ();
			if (rssi == 999)
				modem_status = false;
		}
		
		// bring up the modem's internet stack
		if (modem_status)
			modem_status = ModemCheckIPOpened (APN, 3);
			
		// update the modem's real-time-clock from the network
		if (modem_status)
			modem_status = ModemSyncToHTPTime (HTP_HOSTS, sizeof(HTP_HOSTS) / sizeof(HTP_HOSTS[0]), 3);
			
		// if there was a problem, shut the modem down
		if (! modem_status)
			ModemStop ();
	}
	return modem_status;
}

/**
 * @brief stop the Modem service
 */
static bool ModemServiceDown (void) {
	// bring down modem ...
	bool modem_status = false;
	for (int n_retries = 0; (n_retries < 3) && (! modem_status); n_retries ++) {
		// bring down the modem's internet stack
		modem_status = ModemCheckIPClosed (3);
	}
	ModemStop ();

	return modem_status;
}

/**
 * @brief an error handler used by CubeMX error handlers
 */
 void AppError (void) {
	printf ("\r\nERROR: App error handler called\r\n");

	BlinkLEDForever (LED_SYSTEM_ERROR, WatchdogCallback);
}

/**
 * @brief a callback that prevents HAL's watchdog from restarting the applications
 */
static void WatchdogCallback (void) {
	PingIWDG ();
}
	
